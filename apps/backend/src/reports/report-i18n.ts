const CATALOGS: Record<AppLocale, Record<Key, string>> = {
  pt_BR: pt,
  en_US: en,
  es_ES: es,
};

export type ReportText = (
  key: string,
  params?: Record<string, string | number>,
) => string;

/** Unknown keys come back as the key's last part (never an exception in a report). */
export function reportText(locale: AppLocale): ReportText {
  const catalog = CATALOGS[locale] ?? pt;
  return (key, params = {}) => {
    const template =
      (catalog as Record<string, string>)[key] ?? key.split('.').at(-1) ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  };
}

export function titleOf(locale: AppLocale, type: ReportTypeName): string {
  return reportText(locale)(`type.${type}`);
}

/** BCP 47 for Intl ("pt-BR"). */
export function bcp47(locale: AppLocale): string {
  return locale.replace('_', '-');
}
